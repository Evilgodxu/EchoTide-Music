def main():
    ok = 0
    for name, data, expect in CASES:
        r = match(data)
        got = r is not None
        flag = "PASS" if got == expect else "FAIL"
        if flag == "PASS":
            ok += 1
        print(f"[{flag}] {name:<44} -> {r or '未命中'}")
    print(f"\n{ok}/{len(CASES)} 通过")
    return 0 if ok == len(CASES) else 1


if __name__ == "__main__":
    sys.exit(main())
