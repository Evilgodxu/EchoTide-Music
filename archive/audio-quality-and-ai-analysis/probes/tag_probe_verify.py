"""AiSourceTagProbe 逻辑核验：用构造的 FLAC/ID3 字节精确验证解析偏移与分级匹配。

构造已知结构的合成容器，逐项断言「该命中」与「不该命中」，
覆盖 Vorbis comment、ID3v2 文本帧、内容凭证原始字节三条路径。
"""

from __future__ import annotations

import struct
import sys


def build_flac(vendor: str, comments: dict[str, str], extra_marker: bytes = b"") -> bytes:
    """按 FLAC 块结构拼装：STREAMINFO + VORBIS_COMMENT + 若干音频字节。"""
    body = struct.pack("<I", len(vendor.encode())) + vendor.encode()
    entries = [f"{k}={v}".encode() for k, v in comments.items()]
    body += struct.pack("<I", len(entries))
    for e in entries:
        body += struct.pack("<I", len(e)) + e
    out = b"fLaC"
    out += bytes([0x00]) + len(b"\x00" * 34).to_bytes(3, "big") + b"\x00" * 34
    out += bytes([0x84]) + len(body).to_bytes(3, "big") + body
    out += extra_marker + b"\x00" * 512
    return out


def build_id3v2(frames: list[tuple[str, bytes]]) -> bytes:
    """按 ID3v2.3 帧结构拼装，用于验证 MP3 标签路径。"""
    body = b""
    for fid, payload in frames:
        body += fid.encode() + struct.pack(">I", len(payload)) + b"\x00\x00" + payload
    size = len(body)
    ss = bytes([(size >> 21) & 0x7F, (size >> 14) & 0x7F, (size >> 7) & 0x7F, size & 0x7F])
    return b"ID3\x03\x00\x00" + ss + body + b"\xff\xfb" + b"\x00" * 256


